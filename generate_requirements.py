#!/usr/bin/env python3
"""
Generate requirements.txt by scanning Python imports in a project.

Usage:
    python generate_requirements.py
    python generate_requirements.py --project .
    python generate_requirements.py --output requirements.txt

This maps common import names to pip distribution names where known.
Review the generated file before sharing: static scanning cannot detect every
dynamic import, optional dependency, or external system requirement.
"""

import argparse
import ast
import importlib.metadata
import sys
from pathlib import Path

# Import name -> PyPI distribution name for common packages whose names differ.
KNOWN_DISTRIBUTIONS = {
    "PIL": "Pillow",
    "cv2": "opencv-python",
    "sklearn": "scikit-learn",
    "yaml": "PyYAML",
    "dotenv": "python-dotenv",
    "bs4": "beautifulsoup4",
    "dateutil": "python-dateutil",
    "Crypto": "pycryptodome",
    "fitz": "PyMuPDF",
    "serial": "pyserial",
    "gi": "PyGObject",
    "wx": "wxPython",
    "OpenSSL": "pyOpenSSL",
    "googleapiclient": "google-api-python-client",
    "google_auth_oauthlib": "google-auth-oauthlib",
    "google.auth": "google-auth",
    "skimage": "scikit-image",
    "tensorflow": "tensorflow",
    "torch": "torch",
    "Image": "Pillow",
}

IGNORED_DIRS = {
    ".git", ".venv", "venv", "env", "__pycache__", "node_modules",
    "site-packages", "dist", "build", ".mypy_cache", ".pytest_cache",
}

STDLIB = set(getattr(sys, "stdlib_module_names", ()))

def scan_imports(project: Path):
    modules = set()
    errors = []

    for file in project.rglob("*.py"):
        if any(part in IGNORED_DIRS for part in file.parts):
            continue
        try:
            source = file.read_text(encoding="utf-8")
            tree = ast.parse(source, filename=str(file))
        except (OSError, UnicodeError, SyntaxError) as exc:
            errors.append(f"{file.relative_to(project)}: {exc}")
            continue

        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    modules.add(alias.name.split(".")[0])
            elif isinstance(node, ast.ImportFrom) and node.module:
                if node.level == 0:
                    modules.add(node.module.split(".")[0])

    # Remove standard library modules and likely local project modules.
    local_names = {p.stem for p in project.glob("*.py")}
    local_names.update(
        p.name for p in project.iterdir()
        if p.is_dir() and (p / "__init__.py").exists()
    )
    modules -= STDLIB
    modules -= local_names
    return sorted(modules, key=str.lower), errors

def distribution_name(module: str, installed_map: dict):
    if module in KNOWN_DISTRIBUTIONS:
        return KNOWN_DISTRIBUTIONS[module]
    if module in installed_map:
        return installed_map[module]
    return None

def main():
    parser = argparse.ArgumentParser(
        description="Scan Python imports and write a requirements.txt file."
    )
    parser.add_argument("--project", default=".", help="Project root folder")
    parser.add_argument(
        "--output", default="requirements.txt",
        help="Output file path (default: requirements.txt)"
    )
    args = parser.parse_args()

    project = Path(args.project).resolve()
    if not project.is_dir():
        print(f"Error: project folder does not exist: {project}")
        raise SystemExit(1)

    output = Path(args.output)
    if not output.is_absolute():
        output = project / output

    modules, errors = scan_imports(project)

    # Build import-name -> installed distribution-name mapping from the
    # currently active Python environment.
    installed_map = {}
    try:
        mapping = importlib.metadata.packages_distributions()
        for module, distributions in mapping.items():
            if distributions:
                installed_map[module] = sorted(distributions, key=str.lower)[0]
    except Exception:
        pass

    requirements = set()
    unresolved = []

    for module in modules:
        name = distribution_name(module, installed_map)
        if name:
            requirements.add(name)
        else:
            unresolved.append(module)

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        "# Generated by generate_requirements.py; review before sharing.\n"
        + "".join(f"{name}\n" for name in sorted(requirements, key=str.lower)),
        encoding="utf-8",
    )

    print(f"Scanned project: {project}")
    print(f"Python import names found: {len(modules)}")
    print(f"Mapped package requirements: {len(requirements)}")
    print(f"Created: {output}")

    if unresolved:
        print("\nCould not map these imports to installed PyPI distributions:")
        print("  " + ", ".join(unresolved))
        print("Check whether they are local modules, standard-library modules,")
        print("or packages that need to be added manually to requirements.txt.")

    if errors:
        print("\nSome files could not be scanned:")
        for error in errors:
            print(f"  - {error}")

    print("\nImportant: review requirements.txt and test it in a clean virtual")
    print("environment. Imports alone cannot discover every runtime dependency.")

if __name__ == "__main__":
    main()
